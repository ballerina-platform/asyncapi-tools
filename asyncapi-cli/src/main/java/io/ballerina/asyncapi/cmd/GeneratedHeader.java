package io.ballerina.asyncapi.cmd;

import io.ballerina.asyncapi.cmd.AsyncApiCmdToolException.InputDiagnostic;
import io.ballerina.asyncapi.cmd.AsyncApiCmdToolException.Kind;

import java.io.IOException;
import java.nio.charset.MalformedInputException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;

/**
 * The top of every generated .bal file: the {@code --license} header, a blank line, a notice that the file is
 * generated, then the source, all with LF line endings (IO-2, IO-3, GEN-2 and GEN-3 of the Ballerina CLI Tool Design
 * Guide). The CLI adds it to whatever the generators wrote, so every protocol gets the same header.
 */
final class GeneratedHeader {

    static final String NOTICE = "// This file is generated by bal asyncapi.";

    private GeneratedHeader() {
    }

    /**
     * Reads a license file and checks it holds only Ballerina comment lines and blank lines, so the generated
     * sources still compile.
     *
     * @param licensePath the file given with {@code --license}
     * @return the license with LF line endings and no trailing blank lines
     * @throws AsyncApiCmdToolException if the file can't be read or has a line that isn't a comment
     */
    static String readLicense(String licensePath) {
        String content;
        try {
            content = Files.readString(Path.of(licensePath));
        } catch (MalformedInputException e) {
            throw AsyncApiCmdToolException.of(Kind.INVALID_INPUT,
                    "license file '" + licensePath + "' is not UTF-8 text")
                    .withSuggestion("Save the license file as UTF-8 text.");
        } catch (IOException | RuntimeException e) {
            throw AsyncApiCmdToolException.of(Kind.INVALID_INPUT, "cannot read license file '" + licensePath + "'")
                    .withSuggestion("Pass a license file that exists and is readable.");
        }
        String[] lines = content.replace("\r\n", "\n").split("\n", -1);
        for (int i = 0; i < lines.length; i++) {
            String line = lines[i].strip();
            if (!line.isEmpty() && !line.startsWith("//")) {
                throw AsyncApiCmdToolException.of(Kind.INVALID_INPUT,
                                "license file '" + licensePath + "' has a line that is not a Ballerina comment")
                        .withDiagnostics(List.of(new InputDiagnostic(licensePath.replace('\\', '/'), i + 1,
                                lines[i].indexOf(line) + 1, "error", "expected a comment starting with //")))
                        .withSuggestion("Start every non-blank line of the license with //.");
            }
        }
        return String.join("\n", lines).stripTrailing();
    }

    /**
     * Adds the license, the notice and LF line endings to every .bal file a generator wrote.
     *
     * @param stagingDir where the generator wrote its files
     * @param license    the license from {@link #readLicense}, or an empty string
     * @throws IOException if a file can't be read or written
     */
    static void apply(Path stagingDir, String license) throws IOException {
        List<Path> sources;
        try (Stream<Path> files = Files.walk(stagingDir)) {
            sources = files.filter(Files::isRegularFile)
                    .filter(file -> file.getFileName().toString().endsWith(CmdConstants.BAL_EXTENSION))
                    .toList();
        }
        String top = (license.isEmpty() ? "" : license + "\n\n") + NOTICE + "\n\n";
        for (Path source : sources) {
            String content = Files.readString(source).replace("\r\n", "\n");
            Files.writeString(source, top + content.stripLeading());
        }
    }
}
