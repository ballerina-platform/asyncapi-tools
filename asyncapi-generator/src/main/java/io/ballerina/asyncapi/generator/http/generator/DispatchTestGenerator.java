package io.ballerina.asyncapi.generator.http.generator;

import io.ballerina.asyncapi.core.model.component.AsyncApiSchema;
import io.ballerina.asyncapi.generator.GeneratorException;
import io.ballerina.asyncapi.generator.http.model.DispatchTestCase;
import io.ballerina.asyncapi.generator.http.model.WebhookAuthConfig;
import io.ballerina.asyncapi.generator.http.utils.CodegenUtils;
import io.ballerina.asyncapi.generator.http.utils.HeaderTemplateParser;
import io.ballerina.asyncapi.generator.http.utils.HeaderTemplateParser.HeaderTemplate;
import io.ballerina.compiler.syntax.tree.SyntaxTree;
import io.ballerina.tools.text.TextDocument;
import io.ballerina.tools.text.TextDocuments;
import org.ballerinalang.formatter.core.Formatter;
import org.ballerinalang.formatter.core.FormatterException;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Generates {@code tests/dispatch_test.bal}: one real {@code @test:Config} dispatch-verification
 * test per event defined in the spec, plus one stub service implementation per service type
 * covering every one of its remote functions.
 *
 * <p>Each test sends a signed HTTP request built from a same-named JSON fixture (expected at
 * {@code <payloadDir>/<eventIdentifier>.json}, not generated by this class -- fixtures are
 * curated data, not synthesizable from a schema alone) to a listener started on a dedicated test
 * port, then asserts the expected remote function fired.
 *
 * <p>Signing currently supports a single HMAC-SHA256 digest of the raw body, hex-encoded, spliced
 * into the configured {@code headerFormat} (literal prefix/suffix text around a single
 * {@code signature} placeholder, e.g. {@code "sha256=$signature"} -- the scheme GitHub's spec
 * uses). Other algorithms/encodings, and richer {@code headerFormat}s with additional placeholders
 * or {@code $config}/{@code $header} composition, are not yet supported by this generator and are
 * out of scope for this pass.
 */
public class DispatchTestGenerator {

    private static final String DEFAULT_PAYLOAD_DIR = "tests/resources/trigger_payloads";
    private static final int TEST_PORT = 9091;
    private static final String TEST_SECRET = "trigger-test-secret";

    private final List<DispatchTestCase> testCases;
    private final WebhookAuthConfig webhookAuthConfig;
    private final Map<String, Set<String>> renamedKeysByType;

    /**
     * Creates a generator for the given dispatch test cases and webhook auth configuration.
     *
     * @param testCases         the extracted dispatch test cases, one per event
     * @param webhookAuthConfig the webhook authentication configuration (header name, algorithm)
     */
    public DispatchTestGenerator(List<DispatchTestCase> testCases, WebhookAuthConfig webhookAuthConfig) {
        this(testCases, webhookAuthConfig, Map.of());
    }

    /**
     * Creates a generator that also asserts renamed fields survive payload binding.
     *
     * @param testCases         the extracted dispatch test cases, one per event
     * @param webhookAuthConfig the webhook authentication configuration (header name, algorithm)
     * @param schemas           the schema map, used to work out which raw JSON keys each payload
     *                          type re-emits under a camelCase field name
     */
    public DispatchTestGenerator(List<DispatchTestCase> testCases, WebhookAuthConfig webhookAuthConfig,
            Map<String, AsyncApiSchema> schemas) {
        this.testCases = testCases;
        this.webhookAuthConfig = webhookAuthConfig;
        this.renamedKeysByType = resolveRenamedKeys(schemas);
    }

    /**
     * Maps each payload type name to the raw JSON keys it re-emits under a camelCase field.
     *
     * <p>Binding failures in this area are silent - a field whose annotation is not honoured comes
     * back {@code nil} while its raw key sits unreachable in the rest descriptor, with no error
     * raised. Knowing the renamed keys lets the generated tests assert on exactly that.
     */
    private static Map<String, Set<String>> resolveRenamedKeys(Map<String, AsyncApiSchema> schemas) {
        Map<String, Set<String>> renamed = new LinkedHashMap<>();
        for (Map.Entry<String, AsyncApiSchema> entry : schemas.entrySet()) {
            AsyncApiSchema schema = entry.getValue();
            if (schema == null || schema.properties() == null) {
                continue;
            }
            Set<String> keys = new LinkedHashSet<>();
            CodegenUtils.resolveFieldNames(schema.properties().keySet()).forEach((rawKey, fieldName) -> {
                if (!rawKey.equals(fieldName)) {
                    keys.add(rawKey);
                }
            });
            if (!keys.isEmpty()) {
                renamed.put(CodegenUtils.getValidName(CodegenUtils.escapeIdentifier(entry.getKey().trim()), true),
                        keys);
            }
        }
        return renamed;
    }

    /**
     * Generates the full content for {@code tests/dispatch_test.bal}.
     *
     * @return the generated Ballerina source string
     * @throws GeneratorException if the test cases are empty or the source fails to parse/format
     */
    public String generate() throws GeneratorException {
        if (testCases.isEmpty()) {
            throw new GeneratorException("No dispatch test cases to generate");
        }

        Map<String, List<DispatchTestCase>> byService = new LinkedHashMap<>();
        for (DispatchTestCase testCase : testCases) {
            byService.computeIfAbsent(testCase.serviceTypeName(), k -> new ArrayList<>()).add(testCase);
        }

        StringBuilder source = new StringBuilder();
        source.append(buildHeader());

        for (Map.Entry<String, List<DispatchTestCase>> entry : byService.entrySet()) {
            source.append(buildServiceStub(entry.getKey(), entry.getValue()));
        }

        source.append(buildSendHelper());
        source.append(buildWaitHelper());

        for (DispatchTestCase testCase : testCases) {
            source.append(buildTestFunction(testCase));
        }

        SyntaxTree syntaxTree = parse(source.toString());
        try {
            return Formatter.format(syntaxTree).toSourceCode();
        } catch (FormatterException e) {
            throw new GeneratorException("Could not format the generated dispatch_test.bal code", e);
        }
    }

    private SyntaxTree parse(String sourceText) {
        TextDocument textDocument = TextDocuments.from(sourceText);
        return SyntaxTree.from(textDocument);
    }

    private String buildHeader() {
        return "import ballerina/test;\n"
                + "import ballerina/http;\n"
                + "import ballerina/crypto;\n"
                + "import ballerina/io;\n"
                + "import ballerina/lang.runtime;\n\n"
                + "const string TRIGGER_TEST_SECRET = \"" + TEST_SECRET + "\";\n"
                + "const int TRIGGER_TEST_PORT = " + TEST_PORT + ";\n"
                + "const string TRIGGER_PAYLOAD_DIR = \"" + DEFAULT_PAYLOAD_DIR + "\";\n\n"
                + "map<boolean> triggerFired = {};\n"
                + "map<json> boundPayloads = {};\n\n"
                + "listener Listener triggerTestListener = "
                + "check new ({webhookSecret: TRIGGER_TEST_SECRET}, TRIGGER_TEST_PORT);\n\n";
    }

    private String buildServiceStub(String serviceTypeName, List<DispatchTestCase> functions) {
        StringBuilder sb = new StringBuilder();
        sb.append("service ").append(serviceTypeName).append(" on triggerTestListener {\n");
        for (DispatchTestCase testCase : functions) {
            String trackerKey = serviceTypeName + "." + testCase.functionName();
            sb.append("    remote function ").append(testCase.functionName())
                    .append("(").append(testCase.payloadTypeName()).append(" payload) returns error? {\n")
                    .append("        triggerFired[\"").append(trackerKey).append("\"] = true;\n");
            if (renamedKeysByType.containsKey(testCase.payloadTypeName())) {
                sb.append("        boundPayloads[\"").append(trackerKey).append("\"] = payload.toJson();\n");
            }
            sb.append("    }\n");
        }
        sb.append("}\n\n");
        return sb.toString();
    }

    private String buildSendHelper() throws GeneratorException {
        String signatureHeader = webhookAuthConfig != null && webhookAuthConfig.headerName() != null
                ? webhookAuthConfig.headerName()
                : "X-Hub-Signature-256";
        String headerFormat = webhookAuthConfig != null ? webhookAuthConfig.headerFormat() : null;
        HeaderTemplate template = HeaderTemplateParser.parse(headerFormat);
        String signatureExpr = buildSignatureExpression(template);
        return "isolated function sendSignedTriggerWebhook(string headerValue, string eventIdentifier) "
                + "returns http:Response|error {\n"
                + "    byte[] body = check io:fileReadBytes(string `${TRIGGER_PAYLOAD_DIR}/${eventIdentifier}.json`);\n"
                + "    byte[] digest = check crypto:hmacSha256(body, TRIGGER_TEST_SECRET.toBytes());\n"
                + "    string computedSignature = digest.toBase16();\n"
                + "    string signature = " + signatureExpr + ";\n\n"
                + "    http:Client triggerClient = check new (string `http://localhost:${TRIGGER_TEST_PORT}`);\n"
                + "    http:Request request = new;\n"
                + "    request.setBinaryPayload(body, contentType = \"application/json\");\n"
                + "    request.setHeader(\"X-GitHub-Event\", headerValue);\n"
                + "    request.setHeader(\"" + signatureHeader + "\", signature);\n"
                + "    return triggerClient->post(\"/\", request);\n"
                + "}\n\n";
    }

    /**
     * Builds a Ballerina string-template expression that splices the computed signature into the
     * configured {@code headerFormat}, e.g. {@code headerFormat = "sha256=$signature"} becomes
     * {@code string `sha256=${computedSignature}`}. Only the {@code signature} placeholder is
     * substituted -- see the class-level doc for the scope of {@code headerFormat}s supported.
     *
     * @param template the parsed {@code headerFormat}
     * @return a Ballerina expression, as source text, evaluating to the full header value
     */
    private String buildSignatureExpression(HeaderTemplate template) {
        StringBuilder expression = new StringBuilder("string `");
        for (int i = 0; i < template.variables().size(); i++) {
            expression.append(escapeBacktickTemplate(template.literals().get(i)));
            String variable = template.variables().get(i);
            expression.append("${").append("signature".equals(variable) ? "computedSignature" : variable)
                    .append("}");
        }
        expression.append(escapeBacktickTemplate(template.literals().get(template.literals().size() - 1)));
        expression.append("`");
        return expression.toString();
    }

    private String escapeBacktickTemplate(String value) {
        return value.replace("\\", "\\\\").replace("`", "\\`");
    }

    private String buildTestFunction(DispatchTestCase testCase) {
        String testFnName = "test" + capitalize(testCase.functionName().replaceFirst("^on", "")) + "Dispatch";
        String trackerKey = testCase.serviceTypeName() + "." + testCase.functionName();
        return "@test:Config {}\n"
                + "function " + testFnName + "() returns error? {\n"
                + "    http:Response response = check sendSignedTriggerWebhook(\""
                + testCase.headerValue() + "\", \"" + testCase.eventIdentifier() + "\");\n"
                + "    test:assertEquals(response.statusCode, http:STATUS_OK);\n"
                + "    test:assertTrue(waitForDispatch(\"" + trackerKey + "\"), \""
                + trackerKey + " should have fired\");\n"
                + buildBindingAssertions(testCase, trackerKey)
                + "}\n\n";
    }

    /**
     * Emits assertions that every renamed field actually bound, for payload types that have any.
     *
     * <p>A rename that is not honoured fails silently: the field reads {@code nil} while its raw
     * key sits in the rest descriptor, so asserting only that the right handler fired would pass
     * either way. Checking that no raw key survived on the bound payload is what makes the
     * regression visible. A fixture that happens not to carry the key passes trivially, which is
     * correct - there is nothing to bind in that case.
     */
    private String buildBindingAssertions(DispatchTestCase testCase, String trackerKey) {
        Set<String> renamedKeys = renamedKeysByType.get(testCase.payloadTypeName());
        if (renamedKeys == null || renamedKeys.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        sb.append("    map<json> bound = <map<json>>boundPayloads[\"").append(trackerKey).append("\"];\n");
        for (String rawKey : renamedKeys) {
            sb.append("    test:assertFalse(bound.hasKey(\"").append(rawKey).append("\"), \"'")
                    .append(rawKey).append("' should have bound to its camelCase field on ")
                    .append(testCase.payloadTypeName()).append(", not stayed a raw key\");\n");
        }
        return sb.toString();
    }

    /**
     * Emits the {@code waitForDispatch} helper: the dispatcher acks before invoking the user's
     * handler, so the HTTP response the test client receives does not guarantee the handler has
     * finished running yet on the server side. Polls {@code triggerFired} briefly instead of
     * checking it once immediately after the response returns.
     */
    private String buildWaitHelper() {
        return "function waitForDispatch(string trackerKey) returns boolean {\n"
                + "    foreach int i in 0 ..< 20 {\n"
                + "        if triggerFired[trackerKey] ?: false {\n"
                + "            return true;\n"
                + "        }\n"
                + "        runtime:sleep(0.05);\n"
                + "    }\n"
                + "    return false;\n"
                + "}\n\n";
    }

    private String capitalize(String value) {
        if (value.isEmpty()) {
            return value;
        }
        return Character.toUpperCase(value.charAt(0)) + value.substring(1);
    }
}
